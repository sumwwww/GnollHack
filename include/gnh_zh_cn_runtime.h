static int gnh_zh_has_cjk(const char *s)
{
    if (!s) return 0;
    while (*s) {
        if (((unsigned char)*s) >= 0x80) return 1;
        s++;
    }
    return 0;
}

static const char *gnh_zh_lookup_msg_template(const char *fmt)
{
    if (!fmt || !*fmt) return fmt;
    int lo = 0;
    int hi = 2014;
    while (lo <= hi) {
        int mid = (lo + hi) / 2;
        int cmp = strcmp(gnh_zh_msg_template_table[mid].en, fmt);
        if (cmp == 0) return gnh_zh_msg_template_table[mid].zh;
        if (cmp < 0) lo = mid + 1;
        else hi = mid - 1;
    }
    return fmt;
}

static const char *gnh_zh_fix_pline_fmt(const char *line, char *out_buf, size_t out_sz)
{
    if (!line || !*line || !out_buf || out_sz < 16) return line;
    const struct { const char *en_pre; size_t en_len; const char *zh_pre; } prefixes[] = {
        { "You feel ", 9, "你感到" },
        { "You hear ", 9, "你听到" },
        { "You can't ", 10, "你无法" },
        { "You see ", 8, "你看到" },
        { "Your ", 5, "你的" },
        { "You ", 4, "你" },
        { "There ", 6, "" },
        { "The ", 4, "" },
        { NULL, 0, NULL }
    };
    for (int i = 0; prefixes[i].en_pre != NULL; ++i) {
        if (strncmp(line, prefixes[i].en_pre, prefixes[i].en_len) == 0) {
            const char *rest = line + prefixes[i].en_len;
            const char *tr_rest = gnh_zh_lookup_msg_template(rest);
            if (tr_rest != rest || gnh_zh_has_cjk(tr_rest)) {
                snprintf(out_buf, out_sz, "%s%s", prefixes[i].zh_pre, tr_rest);
                return out_buf;
            }
        }
    }
    return gnh_zh_lookup_msg_template(line);
}

